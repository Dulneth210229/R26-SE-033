def _quality_view_html(data: dict[str, Any]) -> str:
    parts = []
    for key, title in [
        ("performance", "Performance"),
        ("usability", "Usability"),
        ("reliability", "Reliability"),
        ("scalability", "Scalability"),
        ("maintainability", "Maintainability"),
        ("accessibility", "Accessibility"),
    ]:
        parts.append(f'<h3 class="subsection-title">{title}</h3>')
        parts.append(_generic_list(data.get(key, [])))
    return "".join(parts)


def _implementation_tasks_html(tasks: list[Any]) -> str:
    if not tasks:
        return '<p class="empty-note">Not specified.</p>'
    rows = []
    for task in tasks:
        if not isinstance(task, dict):
            rows.append(f"<tr><td colspan='4'>{_esc(task)}</td></tr>")
            continue
        rows.append(
            f"<tr><td>{_esc(task.get('task_id', 'TASK'))}</td>"
            f"<td>{_esc(task.get('task', task.get('description', 'Not specified.')))}</td>"
            f"<td>{_esc(task.get('layer', 'N/A'))}</td>"
            f"<td>{_esc(_join(task.get('suggested_files', [])))}</td></tr>"
        )
    return (
        '<table class="data-table"><thead><tr><th>Task ID</th><th>Task</th><th>Layer</th>'
        f"<th>Suggested Files</th></tr></thead><tbody>{''.join(rows)}</tbody></table>"
    )


def _traceability_matrix_html(items: list[Any]) -> str:
    if not items:
        return '<p class="empty-note">Not specified.</p>'
    rows = []
    for item in items:
        if not isinstance(item, dict):
            continue
        section = item.get("architecture_plan_section") or item.get("sds_section") or "N/A"
        element = item.get("design_element") or item.get("task") or "N/A"
        rows.append(
            f"<tr><td>{_esc(item.get('source_id', 'N/A'))}</td><td>{_esc(item.get('source_type', 'N/A'))}</td>"
            f"<td>{_esc(section)}</td><td>{_esc(element)}</td>"
            f"<td>{_esc(item.get('coverage_status', 'covered'))}</td></tr>"
        )
    return (
        '<table class="data-table"><thead><tr><th>Source ID</th><th>Source Type</th>'
        "<th>Architecture Plan Section</th><th>Design / Task Element</th><th>Coverage</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table>"
    )


def build_architecture_plan_html(architecture_plan_json: dict[str, Any]) -> str:
    """
    Build a complete, self-contained Architecture Plan HTML document.
    """
    document_control = architecture_plan_json.get("document_control", {})
    feature_overview = architecture_plan_json.get("feature_overview", {})
    requirement_interpretation = architecture_plan_json.get("requirement_interpretation", {})
    architecture_approach = architecture_plan_json.get("architecture_approach", {})
    design_views = architecture_plan_json.get("design_views", {})

    feature_name = (
        document_control.get("feature_name")
        or architecture_plan_json.get("feature_name")
        or "Untitled Feature"
    )

    sections = [
        _section(1, "Document Control", _document_control_table(document_control)),
        _section(2, "Feature Overview", _feature_overview_html(feature_overview)),
        _section(3, "Requirement Interpretation", _requirement_interpretation_html(requirement_interpretation)),
        _section(4, "Architecture Approach", _architecture_approach_html(architecture_approach)),
        _section(
            5,
            "Frontend Architecture Plan",
            _frontend_plan_html(architecture_plan_json.get("frontend_architecture_plan", {}), design_views),
        ),
        _section(
            6,
            "Backend Architecture Plan",
            _backend_plan_html(architecture_plan_json.get("backend_architecture_plan", {}), design_views),
        ),
        _section(
            7,
            "End-to-End Implementation Plan (Coder Agent Blueprint)",
            _implementation_plan_html(architecture_plan_json.get("implementation_plan", {})),
        ),
        _section(8, "API and Interface Plan", _interface_view_html(design_views.get("interface_view", {}))),
        _section(9, "Data Model Plan", _data_view_html(design_views.get("data_view", {}))),
        _section(
            10,
            "Validation Plan",
            _validation_plan_html(architecture_plan_json.get("validation_plan", {}), design_views),
        ),
        _section(11, "Error Handling Plan", _error_handling_html(design_views.get("error_handling_view", {}))),
        _section(12, "Security Plan", _security_view_html(design_views.get("security_authorization_view", {}))),
        _section(13, "Quality / NFR Plan", _quality_view_html(design_views.get("quality_attributes_view", {}))),
        _section(
            14, "Coder Implementation Tasks", _implementation_tasks_html(architecture_plan_json.get("coder_implementation_tasks", []))
        ),
        _section(
            15,
            "Requirement-to-Architecture Traceability",
            _traceability_matrix_html(architecture_plan_json.get("traceability_matrix", [])),
        ),
        _section(
            16,
            "Assumptions, Constraints, Risks, and Dependencies",
            '<h3 class="subsection-title">Assumptions</h3>'
            + _plain_list(architecture_plan_json.get("assumptions", []))
            + '<h3 class="subsection-title">Constraints</h3>'
            + _plain_list(architecture_plan_json.get("constraints", []))
            + '<h3 class="subsection-title">Risks</h3>'
            + _generic_list(architecture_plan_json.get("risks", []))
            + '<h3 class="subsection-title">Dependencies</h3>'
            + _plain_list(architecture_plan_json.get("dependencies", [])),
        ),
        _section(
            17,
            "Human Approval Note",
            _smart_text_block(
                architecture_plan_json.get(
                    "human_approval_note",
                    "This Architecture Plan must be reviewed and approved before the UI/UX "
                    "Agent or Coder Agent starts.",
                )
            ),
        ),
        _section(18, "Document Sign-Off", signature_block_html()),
    ]

    body_html = "".join(sections)
    body_html += (
        '<div class="doc-footer">Generated by AutoForge -- Architecture Agent. '
        "This document is a formatted export of the underlying Architecture Plan artifact.</div>"
    )

    return html_document_shell(
        title=f"Architecture Plan: {feature_name}",
        subtitle="Architecture Agent -- Feature-level Architecture Plan",
        body_html=body_html,
    )
