MAX_GENERIC_COLUMNS = 6


def _inline(value: Any) -> str:
    if isinstance(value, dict):
        return ", ".join(f"{k}: {_inline(v)}" for k, v in value.items())
    if isinstance(value, list):
        return ", ".join(_inline(v) for v in value)
    return str(value)


def _join(items: Any) -> str:
    if not items:
        return "N/A"
    if isinstance(items, list):
        return ", ".join(_inline(item) for item in items)
    return str(items)


def _generic_list(items: list[Any]) -> str:
    """
    Render an arbitrary list of records: a table when every item is a dict
    (columns = union of keys, in first-seen order, capped), otherwise a
    plain bullet list -- a robust fallback for the sub-lists whose exact
    shape can vary (e.g. design_views' less-structured sub-views).
    """
    if not items:
        return '<p class="empty-note">Not specified.</p>'

    if not all(isinstance(item, dict) for item in items):
        return _plain_list([_inline(item) for item in items])

    columns: list[str] = []
    for item in items:
        for key in item.keys():
            if key not in columns:
                columns.append(key)
    columns = columns[:MAX_GENERIC_COLUMNS]

    header = "".join(f"<th>{_esc(col.replace('_', ' ').title())}</th>" for col in columns)
    rows = []
    for item in items:
        cells = "".join(f"<td>{_esc(_inline(item.get(col, '')))}</td>" for col in columns)
        rows.append(f"<tr>{cells}</tr>")

    return f'<table class="data-table"><thead><tr>{header}</tr></thead><tbody>{"".join(rows)}</tbody></table>'


