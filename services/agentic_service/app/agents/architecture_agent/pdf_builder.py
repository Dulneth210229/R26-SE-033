def _backend_plan_html(data: dict[str, Any], design_views: dict[str, Any]) -> str:
    logical_view = design_views.get("logical_view", {})
    layers = data.get("layers") or (
        logical_view.get("domain_services", []) + logical_view.get("data_modules", [])
    )
    return (
        '<h3 class="subsection-title">Backend Responsibilities</h3>'
        + _generic_list(data.get("responsibilities") or logical_view.get("backend_modules", []))
        + '<h3 class="subsection-title">Controller / Service / Data Responsibilities</h3>'
        + _generic_list(layers)
        + '<h3 class="subsection-title">Integration Points</h3>'
        + _generic_list(data.get("integration_points") or logical_view.get("integration_points", []))
    )


def _implementation_plan_html(data: dict[str, Any]) -> str:
    if not isinstance(data, dict) or not data:
        return '<p class="empty-note">Not specified.</p>'

    backend = data.get("backend", {}) or {}
    frontend = data.get("frontend", {}) or {}
    parts = []

    parts.append('<h3 class="subsection-title">Backend Files</h3>')
    files = backend.get("files", []) or []
    if files:
        rows = "".join(
            f"<tr><td>{_esc(item.get('path', ''))}</td><td>{_esc(item.get('action', ''))}</td>"
            f"<td>{_esc(item.get('purpose', ''))}</td></tr>"
            for item in files
            if isinstance(item, dict)
        )
        parts.append(
            '<table class="data-table"><thead><tr><th>Path</th><th>Action</th><th>Purpose</th></tr></thead>'
            f"<tbody>{rows}</tbody></table>"
        )
    else:
        parts.append('<p class="empty-note">None planned.</p>')

    parts.append('<h3 class="subsection-title">Endpoints</h3>')
    endpoints = backend.get("endpoints", []) or []
    if endpoints:
        rows = []
        for item in endpoints:
            if not isinstance(item, dict):
                continue
            fields = "; ".join(
                f"{f.get('field', '')} ({f.get('type', '')}, "
                f"{'required' if f.get('required') else 'optional'})"
                for f in item.get("request_body", []) or []
                if isinstance(f, dict)
            )
            errors = "; ".join(_inline(e) for e in item.get("error_cases", []) or [])
            rows.append(
                f"<tr><td>{_esc(item.get('method', ''))} {_esc(item.get('path', ''))}</td>"
                f"<td>{_esc(fields or '—')}</td><td>{_esc(item.get('response', '—'))}</td>"
                f"<td>{_esc(errors or '—')}</td></tr>"
            )
        parts.append(
            '<table class="data-table"><thead><tr><th>Endpoint</th><th>Request Fields</th>'
            f"<th>Response</th><th>Error Cases</th></tr></thead><tbody>{''.join(rows)}</tbody></table>"
        )
    else:
        parts.append('<p class="empty-note">None planned.</p>')

    parts.append('<h3 class="subsection-title">Data Models</h3>')
    models = backend.get("models", []) or []
    if models:
        rows = []
        for item in models:
            if not isinstance(item, dict):
                continue
            fields = "; ".join(
                f"{f.get('name', '')}: {f.get('type', '')} {f.get('constraints', '')}"
                for f in item.get("fields", []) or []
                if isinstance(f, dict)
            )
            rows.append(
                f"<tr><td>{_esc(item.get('name', ''))}</td><td>{_esc(item.get('file', ''))}</td>"
                f"<td>{_esc(fields or '—')}</td></tr>"
            )
        parts.append(
            '<table class="data-table"><thead><tr><th>Name</th><th>File</th><th>Fields</th></tr></thead>'
            f"<tbody>{''.join(rows)}</tbody></table>"
        )
    else:
        parts.append('<p class="empty-note">None planned.</p>')

    parts.append('<h3 class="subsection-title">Frontend Pages / Components / Services</h3>')
    fe_lines: list[str] = []
    for page in frontend.get("pages", []) or []:
        if isinstance(page, dict):
            fe_lines.append(
                f"Page {page.get('path', '')} at route {page.get('route', '')}: {page.get('purpose', '')}"
            )
    for component in frontend.get("components_to_reuse", []) or []:
        fe_lines.append(f"Reuse approved component: {_inline(component)}")
    for service in frontend.get("services", []) or []:
        if isinstance(service, dict):
            functions = ", ".join(
                f"{f.get('name', '')} -> {f.get('calls_endpoint', '')}"
                for f in service.get("functions", []) or []
                if isinstance(f, dict)
            )
            fe_lines.append(f"Service {service.get('path', '')}: {functions or 'no functions listed'}")
    routing = frontend.get("routing", {}) or {}
    for route in routing.get("new_routes", []) or []:
        fe_lines.append(f"Route: {_inline(route)}")
    for link in routing.get("nav_links", []) or []:
        fe_lines.append(f"Nav link: {_inline(link)}")
    parts.append(_plain_list(fe_lines))

    parts.append('<h3 class="subsection-title">Implementation Order</h3>')
    order = data.get("implementation_order", []) or []
    if order:
        items = "".join(f"<li>{_esc(_inline(step))}</li>" for step in order)
        parts.append(f'<ol class="plain-list">{items}</ol>')
    else:
        parts.append('<p class="empty-note">Not specified.</p>')

    parts.append('<h3 class="subsection-title">Constraints</h3>')
    parts.append(_plain_list(data.get("constraints", []) or []))

    return "".join(parts)


def _interface_view_html(data: dict[str, Any]) -> str:
    endpoints = data.get("api_endpoints", []) or []
    if endpoints:
        rows = []
        for endpoint in endpoints:
            if not isinstance(endpoint, dict):
                rows.append(f"<tr><td colspan='5'>{_esc(endpoint)}</td></tr>")
                continue
            rows.append(
                f"<tr><td>{_esc(endpoint.get('method', 'METHOD'))} {_esc(endpoint.get('endpoint', '/path'))}</td>"
                f"<td>{_esc(endpoint.get('purpose', ''))}</td>"
                f"<td>{_esc(endpoint.get('request_model', 'N/A'))}</td>"
                f"<td>{_esc(endpoint.get('success_response_model', 'N/A'))}</td>"
                f"<td>{_esc(_join(endpoint.get('related_requirements', [])))}</td></tr>"
            )
        endpoints_html = (
            '<table class="data-table"><thead><tr><th>Endpoint</th><th>Purpose</th>'
            "<th>Request Model</th><th>Response Model</th><th>Related Requirements</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table>"
        )
    else:
        endpoints_html = '<p class="empty-note">Not specified.</p>'

    def _models_html(models: list[Any]) -> str:
        if not models:
            return '<p class="empty-note">Not specified.</p>'
        rows = []
        for model in models:
            if not isinstance(model, dict):
                rows.append(f"<tr><td colspan='3'>{_esc(model)}</td></tr>")
                continue
            fields = _join(model.get("fields", []))
            rows.append(
                f"<tr><td>{_esc(model.get('name', 'Model'))}</td><td>{_esc(fields)}</td>"
                f"<td>{_esc(_join(model.get('related_requirements', [])))}</td></tr>"
            )
        return (
            '<table class="data-table"><thead><tr><th>Model</th><th>Fields</th>'
            f"<th>Related Requirements</th></tr></thead><tbody>{''.join(rows)}</tbody></table>"
        )

    return (
        '<h3 class="subsection-title">API Endpoints</h3>'
        + endpoints_html
        + '<h3 class="subsection-title">Request Models</h3>'
        + _models_html(data.get("request_models", []))
        + '<h3 class="subsection-title">Response Models</h3>'
        + _models_html(data.get("response_models", []))
    )


