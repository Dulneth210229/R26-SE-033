"""
Architecture Agent Architecture Plan PDF Builder.

Purpose:
Convert Architecture Plan JSON into a real, table-based HTML document
mirroring the frontend's own ArchitecturePlanDocumentViewer.jsx section order
-- Document Control; Feature Overview; Requirement Interpretation;
Architecture Approach; Frontend/Backend Architecture Plan; Implementation
Plan (backend files/endpoints/models, frontend pages/components/services/
routing, implementation order, constraints); API & Interface Plan; Data
Model Plan; Validation Plan; Error Handling Plan; Security Plan; Quality/NFR
Plan; Coder Implementation Tasks; Requirement-to-Architecture Traceability;
Assumptions/Constraints/Risks/Dependencies; Human Approval Note.

This is a NEW template, not a reuse of ArchitecturePlanMarkdownBuilder's
bulleted Markdown output.
"""

from __future__ import annotations

from typing import Any

from app.agents._shared.pdf_style import html_document_shell, signature_block_html
